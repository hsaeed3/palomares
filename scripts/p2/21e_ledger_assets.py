def ground(x, y):
    z = dtm05.sample(x, y); z2 = dtm1.sample(x, y)
    return np.where(np.isfinite(z), z, z2)


def station_lateral(xy):
    """(s, d) of world points: nearest centreline sample, d > 0 = left"""
    _, j = KD.query(xy[:, :2])
    dx, dy = xy[:, 0] - road.x[j], xy[:, 1] - road.y[j]
    return road.s[j] + dx * road.tx[j] + dy * road.ty[j], dx * road.nx[j] + dy * road.ny[j], j


