def _side(r):
    return 1 if r.get("side", "R") == "L" else -1


# ------------------------------------------------------------------ placement frames
def clamp_off(i, sgn, outer, off, zr):
    """per-sample offset beyond road.outer (arrays): pulled in toward the edge where the ground drops > DROP_MAX"""
    i = np.atleast_1d(i); outer = np.atleast_1d(outer); zr = np.atleast_1d(zr); off = np.broadcast_to(np.asarray(off, float), i.shape)
    fr = np.linspace(1.0, 0.0, 9); cand = np.maximum(off, 0)[:, None] * fr[None, :]
    x, y = road.xy(np.repeat(i[:, None], 9, 1), sgn * (outer[:, None] + cand))
    zg = ground(x, y); ok = np.isfinite(zg) & (zg >= zr[:, None] - DROP_MAX); ok[:, -1] = True
    return np.where(off < 0, off, cand[np.arange(len(i)), ok.argmax(1)])


GROUND_FREE = ("building", "bridge", "marking", "driveway", "tree_add")


class Frame:
    """anchor of a point object: position, ground z, tangent t, outward unit vector"""
    def __init__(self, r):
        s = float(np.clip(r["s"], 1, S_END - 1)); sgn = _side(r); i = min(max(int(round(s)), 0), N - 1)
        off = float(r.get("off") or 0.0)
        outer = float(road.outer(i, sgn)); zr = float(road.surface_z(i, sgn * road.el[i] if sgn > 0 else sgn * road.er[i], noise=False))
        if r["cls"] not in GROUND_FREE and 0 <= off <= FAR:
            off = float(clamp_off(i, sgn, outer, off, zr)[0])
        d = sgn * (outer + off)
        X, Y = float(np.interp(s, road.s, road.x)), float(np.interp(s, road.s, road.y))
        nx, ny = float(np.interp(s, road.s, road.nx)), float(np.interp(s, road.s, road.ny)); nn = math.hypot(nx, ny); nx, ny = nx / nn, ny / nn
        self.t = np.array([ny, -nx]); self.n = np.array([nx, ny]); self.out = self.n * sgn
        self.x, self.y = X + nx * d, Y + ny * d
        zs = float(road.surface_z(i, d, noise=False)) if off <= 0 else float(road.surface_z(i, sgn * outer, noise=False))
        zg = float(ground(np.array([self.x]), np.array([self.y]))[0])
        w = min(max(off / 1.2, 0), 1)
        self.z = (zs * (1 - w) + zg * w if np.isfinite(zg) else zs) + float(r.get("dz") or 0)
        self.s, self.i, self.sgn, self.off, self.zr = s, i, sgn, off, zr


class Line:
    """polyline parallel to road.outer at offset off, terrain-following z, NB order"""
    def __init__(self, r, s0, s1, drape=None):
        s0 = float(np.clip(s0, 1, S_END - 2)); s1 = float(np.clip(s1, s0 + 0.5, S_END - 1)); sgn = _side(r)
        n = max(2, int(math.ceil(s1 - s0)) + 1); ss = np.linspace(s0, s1, n); idx = np.clip(np.round(ss).astype(int), 0, N - 1)
        outer = road.outer(idx, np.full(n, sgn)); off = float(r.get("off") or 0.0)
        e = road.el[idx] if sgn > 0 else road.er[idx]; zr = road.surface_z(idx, sgn * e, noise=False)
        if r["cls"] not in GROUND_FREE and 0 <= off <= FAR:
            raw = clamp_off(idx, sgn, outer, off, zr)
            sm = gaussian_filter1d(minimum_filter1d(raw, 7, mode="nearest"), 2.5, mode="nearest")
            offv = np.maximum(np.minimum(sm, raw), 0)
        else:
            offv = np.full(n, off)
        nx, ny = np.interp(ss, road.s, road.nx), np.interp(ss, road.s, road.ny); nn = np.hypot(nx, ny); nx, ny = nx / nn, ny / nn
        d = sgn * (outer + offv)
        self.x = np.interp(ss, road.s, road.x) + nx * d; self.y = np.interp(ss, road.s, road.y) + ny * d
        zs = road.surface_z(idx, np.where(offv <= 0, d, sgn * outer), noise=False)
        zg = ground(self.x, self.y); w = np.clip(offv / 1.2, 0, 1)
        z = np.where(np.isfinite(zg), zs * (1 - w) + zg * w, zs)
        self.z = gaussian_filter1d(z, 1.5, mode="nearest") + float(r.get("dz") or 0)
        self.cum = np.r_[0, np.cumsum(np.hypot(np.diff(self.x), np.diff(self.y)))]; self.L = float(self.cum[-1])
        t = np.gradient(np.c_[self.x, self.y], axis=0); t /= np.hypot(t[:, 0], t[:, 1])[:, None] + 1e-12
        self.t = t; self.n = np.c_[-t[:, 1], t[:, 0]]; self.sgn = sgn; self.ss = ss; self.idx = idx; self.d = d

    def map(self, P, N_, drape=None):
        """local (x along, y outward, z) -> world; R side is the 180-degree rotation (a = L - x, n' = -n)"""
        a = P[:, 0] if self.sgn > 0 else self.L - P[:, 0]
        a = np.clip(a, 0, self.L)
        x = np.interp(a, self.cum, self.x); y = np.interp(a, self.cum, self.y); z = np.interp(a, self.cum, self.z)
        tx = np.interp(a, self.cum, self.t[:, 0]); ty = np.interp(a, self.cum, self.t[:, 1]); tn = np.hypot(tx, ty) + 1e-12; tx, ty = tx / tn, ty / tn
        k = self.sgn                                        # local x -> k*t, local y -> k*n (n = left)
        W = np.c_[x + k * (-ty) * P[:, 1], y + k * tx * P[:, 1]]
        if drape == "road":
            s_, d_, j = station_lateral(W); Z = road.surface_z(j, d_, noise=False) + P[:, 2]
        elif drape:
            s_, d_, j = station_lateral(W); zr = road.surface_z(j, d_, noise=False); zg = ground(W[:, 0], W[:, 1])
            outer = road.outer(j, np.sign(d_) + (d_ == 0))
            Z = np.where(np.abs(d_) <= outer, zr, np.where(np.isfinite(zg), np.maximum(zg, zr - 0.05 * (np.abs(d_) - outer) - 0.0), zr)) + P[:, 2]
        else:
            Z = z + P[:, 2]
        Nw = np.c_[k * (N_[:, 0] * tx - N_[:, 1] * ty), k * (N_[:, 0] * ty + N_[:, 1] * tx), N_[:, 2]]
        return np.c_[W, Z], Nw


def point_axes(r, f):
    """world (xaxis, yaxis) of a point object's local frame"""
    if r["cls"] == "sign" or (r.get("asset") or "").startswith("post.hazard"):
        sb = (r.get("params") or {}).get("dir", "nb") == "sb"
        face = (f.t if sb else -f.t) * 0.97 - f.out * 0.2; face /= np.linalg.norm(face)
        xa = -face
    else:
        xa = f.t if f.sgn > 0 else -f.t
    yaw = math.radians(float(r.get("yaw") or 0))
    c, s_ = math.cos(yaw), math.sin(yaw); xa = np.array([c * xa[0] - s_ * xa[1], s_ * xa[0] + c * xa[1]])
    return xa, np.array([-xa[1], xa[0]])


# ------------------------------------------------------------------ accumulators
class Acc:
    def __init__(self, c):
        self.P, self.T, self.UV, self.N, self.n = [], [], [], [], 0; self.col = CO.Collider(f"1WALL_lg_{c:02d}")

    def add(self, P, T, UV, N_):
        if len(P):
            self.P.append(P); self.T.append(T + self.n); self.UV.append(UV); self.N.append(N_); self.n += len(P)


class _Chunks(dict):
    def __missing__(self, c):
        self[c] = Acc(c); return self[c]


ACC = _Chunks(); NCH = int(S_END // CHUNK) + 1
chunk_of = lambda s: min(max(int(s // CHUNK), 0), NCH - 1)
SOLID, SIGNCHK, POLES = [], [], {1: [], -1: []}
CNT, SKIP = collections.Counter(), collections.Counter()


def need_col(kind, pts, z, s0, s1):
    SOLID.append(dict(type=kind, s0=float(s0), s1=float(s1), pts=[[round(float(a), 2), round(float(b), 2)] for a, b in pts],
                      z=[round(float(v), 2) for v in z], src="ledger"))


def sign_dir(r, p):
    """21c rule: curve / chevron / arrow direction follows the road curvature ahead of the approaching driver"""
    a = r.get("asset", "")
    if p.get("lock_dir") or not any(k in a for k in ("curve", "chevron", "arrow")):
        return None
    i0 = min(max(int(round(r["s"])), 0), N - 1); nb = p.get("dir", "nb") != "sb"
    dh = float(road.k[i0:i0 + 45].sum()) if nb else -float(road.k[max(i0 - 45, 0):i0 + 1].sum())
    return ("left" if dh > 0 else "right") if abs(dh) > 0.09 else None


def place_point(r, cat):
    f = Frame(r); p = dict(r.get("params") or {}); p.setdefault("seed", zlib.crc32(r["id"].encode()) & 0xffff)
    if r["cls"] == "sign":
        p["_dir"] = sign_dir(r, p)
    if r.get("scale") not in (None, 1, 1.0):
        p.setdefault("scale", float(r["scale"]))
    m = AS.generate(r["asset"], None, p); P, T, UV, N_ = m.arrays()
    xa, ya = point_axes(r, f)
    W = np.c_[f.x + P[:, 0] * xa[0] + P[:, 1] * ya[0], f.y + P[:, 0] * xa[1] + P[:, 1] * ya[1]]
    if m.meta.get("drape"):
        Z = np.where(np.isfinite(g := ground(W[:, 0], W[:, 1])), g, f.z) + P[:, 2]
    else:
        Z = f.z + P[:, 2]
    Nw = np.c_[N_[:, 0] * xa[0] + N_[:, 1] * ya[0], N_[:, 0] * xa[1] + N_[:, 1] * ya[1], N_[:, 2]]
    acc = ACC[chunk_of(f.s)]; base = acc.n
    acc.add(np.c_[W, Z], T, UV, Nw)
    if "front" in m.meta:
        k = m.meta["front"]; nb = p.get("dir", "nb") != "sb"
        face = -xa
        SIGNCHK.append(dict(s=float(f.s), key=m.meta["key"], nb=bool(nb), t=[float(f.t[0]), float(f.t[1])], face=[float(face[0]), float(face[1])],
                            cdir=p.get("_dir"), P=np.round(np.c_[W, Z][k:k + 4], 3).tolist(), UV=np.round(UV[k:k + 4], 5).tolist(),
                            N=np.round(Nw[k], 3).tolist(), rect=[], src="ledger", id=r["id"]))
    lim = 15.0 if r["cls"] == "building" else FAR
    if cat.get("collision") and f.off <= lim:
        for c in m.col:
            if c[0] == "box":
                _, cx, cy, L, Wd, z0, z1, yaw = c
                fw = xa * math.cos(yaw) + ya * math.sin(yaw)
                X = f.x + cx * xa[0] + cy * ya[0]; Y = f.y + cx * xa[1] + cy * ya[1]
                acc.col.box(X, Y, fw, L, Wd, f.z + z0, f.z + z1)
                need_col(r["asset"], [(X, Y)], [f.z], f.s, f.s)
    elif cat.get("collision"):
        SKIP[r["cls"]] += 1
    if r["cls"] == "pole" and "wire_z" in m.meta:
        POLES[f.sgn].append((f.s, f.x, f.y, f.z + m.meta["wire_z"], ya, m.meta["wire_dy"]))


def place_linear(r, cat):
    s0, s1 = float(r["s"]), float(r["s1"] if r.get("s1") is not None else r["s"] + 4.0)
    p = dict(r.get("params") or {}); p.setdefault("seed", zlib.crc32(r["id"].encode()) & 0xffff)
    ln = Line(r, s0, s1)
    # split at chunk boundaries so each piece lands in its own chunk mesh
    cuts = [s0] + [c * CHUNK for c in range(int(s0 // CHUNK) + 1, int(s1 // CHUNK) + 1) if s0 < c * CHUNK < s1] + [s1]
    m = AS.generate(r["asset"], ln.L, p); P, T, UV, N_ = m.arrays()
    if not len(P):
        return
    drape = m.meta.get("drape")
    Pw, Nw = ln.map(P, N_, drape=drape)
    # assign triangles to chunks by their station
    tc = Pw[T].mean(1); s_tri, _, _ = station_lateral(tc)
    ch = np.array([chunk_of(v) for v in s_tri])
    for c in np.unique(ch):
        tt = T[ch == c]; used, inv = np.unique(tt, return_inverse=True)
        ACC[c].add(Pw[used], inv.reshape(-1, 3), UV[used], Nw[used])
    far = (float(r.get("off") or 0) > FAR) and r["cls"] != "bridge"
    if cat.get("collision") and not far:
        for c in m.col:
            if c[0] != "line":
                continue
            _, yl, z0, z1, half = c
            a = np.unique(np.r_[np.arange(-0.5, ln.L + 0.5, 1.0), ln.L + 0.5])
            Q = np.c_[np.clip(a if ln.sgn > 0 else ln.L - a, -0.5, ln.L + 0.5), np.full(len(a), yl), np.zeros(len(a))]
            Wq, _ = ln.map(Q, np.zeros_like(Q))
            # extend 0.5 m past the ends along the tangent (map() clips a to [0, L])
            for e_, sg in ((0, -1), (-1, 1)):
                tdir = ln.t[0 if e_ == 0 else -1] * sg
                Wq[e_, :2] = Wq[e_, :2] + tdir * 0.5
            sq, _, _ = station_lateral(Wq); chq = np.array([chunk_of(v) for v in sq])
            for cc in np.unique(chq):
                k = np.nonzero(chq == cc)[0]
                k = np.unique(np.r_[max(k[0] - 1, 0), k, min(k[-1] + 1, len(Wq) - 1)])
                if len(k) < 2:
                    continue
                ACC[cc].col.ribbon(Wq[k, 0], Wq[k, 1], Wq[k, 2] + z0, Wq[k, 2] + z1, half)
            need_col(r["asset"], Wq[:, :2], Wq[:, 2], s0, s1)
        for c in m.col:
            if c[0] == "box":                             # e.g. cypress trunks along a row
                _, cx, cy, L, Wd, z0, z1, yaw = c
                Q, _ = ln.map(np.array([[cx, cy, 0.0]]), np.zeros((1, 3)))
                sq, _, j = station_lateral(Q)
                ACC[chunk_of(sq[0])].col.box(Q[0, 0], Q[0, 1], (road.tx[j[0]], road.ty[j[0]]), L, Wd, Q[0, 2] + z0, Q[0, 2] + z1)
                need_col(r["asset"], [(Q[0, 0], Q[0, 1])], [Q[0, 2]], s0, s1)
    elif cat.get("collision"):
        SKIP[r["cls"]] += 1


def do_wires():
    for sgn, lst in POLES.items():
        lst.sort(key=lambda q: q[0])
        for A, B in zip(lst[:-1], lst[1:]):
            if B[0] - A[0] > 90:
                continue
            span = math.hypot(B[1] - A[1], B[2] - A[2]); sag = 0.0004 * span * span + 0.1
            u = np.linspace(0, 1, max(3, int(span / 4))); rb = AS.R("black")
            for dy in A[5]:
                x = A[1] + A[4][0] * dy + (B[1] + B[4][0] * dy - A[1] - A[4][0] * dy) * u
                y = A[2] + A[4][1] * dy + (B[2] + B[4][1] * dy - A[2] - A[4][1] * dy) * u
                z = A[3] + (B[3] - A[3]) * u - sag * 4 * u * (1 - u)
                mb = AS.MB()
                for k in range(len(u) - 1):
                    mb.quad2([[x[k], y[k], z[k] - 0.02], [x[k + 1], y[k + 1], z[k + 1] - 0.02], [x[k + 1], y[k + 1], z[k + 1] + 0.02], [x[k], y[k], z[k] + 0.02]], rb)
                P, T, UV, N_ = mb.arrays(); ACC[chunk_of(A[0])].add(P, T, UV, N_)


# ------------------------------------------------------------------ terrain / vegetation edits
def terrain_edits(rows):
    eds = [r for r in rows if r["cls"] in ("mound", "ditch")]
    if not eds:
        return 0
    nv = 0
    for m in G["terrain"]:
        if not m["name"].startswith("1GRASS_t"):
            continue
        P = m["P"]; dz = np.zeros(len(P))
        lo, hi = P[:, :2].min(0) - 60, P[:, :2].max(0) + 60
        sl = dl = jj = None
        for r in eds:
            f = Frame(r)
            if not (lo[0] < f.x < hi[0] and lo[1] < f.y < hi[1]):
                continue
            pr = r.get("params") or {}; rad = float(pr.get("radius", 3.0)); h = abs(float(pr.get("height", 0.6)))
            h = -h if r["cls"] == "ditch" else h; length = float(pr.get("length", 0.0))
            near = np.nonzero(np.hypot(P[:, 0] - f.x, P[:, 1] - f.y) < rad * 3 + length)[0]
            if not len(near):
                continue
            if sl is None:
                sl, dl, jj = station_lateral(P)
            ds = np.maximum(np.abs(sl[near] - f.s) - length / 2, 0); dd = dl[near] - f.sgn * (road.outer(f.i, f.sgn) + f.off)
            dist = np.hypot(ds, dd)
            if pr.get("shape") == "capsule":
                w = np.clip(1 - (dist / rad) ** 2, 0, 1) ** 2
            else:
                w = np.exp(-0.5 * (dist / (rad / 2)) ** 2)
            keep = np.abs(dl[near]) > road.outer(jj[near], np.sign(dl[near]) + (dl[near] == 0)) + 0.3
            dz[near] += h * w * keep
        idx = np.nonzero(np.abs(dz) > 1e-4)[0]
        if len(idx):
            m["P"] = P.copy(); m["P"][idx, 2] += dz[idx]; m["N"] = vertex_normals(m["P"], m["T"].reshape(-1, 3))
            ST["dz"][f"terrain/{m['name']}"] = (idx, dz[idx]); nv += len(idx)
    return nv


def drop_tris(gname, m, mask):
    T = m["T"].reshape(-1, 3)
    if mask.any():
        ST["removed"].setdefault(f"{gname}/{m['name']}", np.zeros((0, 3), T.dtype))
        k = f"{gname}/{m['name']}"; ST["removed"][k] = np.concatenate([ST["removed"][k], T[mask]]); m["T"] = T[~mask]
    return int(mask.sum())


def tree_edits(rows):
    rem = [r for r in rows if r["cls"] == "tree_remove"]; den = [r for r in rows if r["cls"] == "tree_density"]
    n_rm = n_thin = n_add = 0
    pts = [(Frame(r), float((r.get("params") or {}).get("radius", 5.0))) for r in rem]
    for m in G["trees"]:
        T = m["T"].reshape(-1, 3)
        if not len(T):
            continue
        C = m["P"][T].mean(1)
        mask = np.zeros(len(T), bool)
        if pts and m["material"] in ("tree_leaves", "tree_trunk", "invisible"):
            for f, rad in pts:
                mask |= np.hypot(C[:, 0] - f.x, C[:, 1] - f.y) < rad
            n_rm += drop_tris("trees", m, mask)
        if den and m["material"] == "shrub":
            T = m["T"].reshape(-1, 3); C = m["P"][T].mean(1); s_, d_, _ = station_lateral(C); mask = np.zeros(len(T), bool)
            key = (np.floor(C[:, 0]).astype(np.int64) * 73856093) ^ (np.floor(C[:, 1]).astype(np.int64) * 19349663)
            u = (key % 1000) / 1000.0                     # same value for all quads of one clump (same metre cell)
            for r in den:
                mult = float((r.get("params") or {}).get("mult", (r.get("params") or {}).get("density", 1.0)))
                if mult >= 1:
                    continue
                sgn = _side(r); off = float(r.get("off") or 0); wd = float((r.get("params") or {}).get("width", 15.0))
                band = (s_ >= r["s"]) & (s_ <= float(r.get("s1") or r["s"])) & (np.sign(d_) == sgn)
                ad = np.abs(d_); i_ = np.clip(np.round(s_).astype(int), 0, N - 1); o_ = road.outer(i_, np.full(len(i_), sgn))
                band &= (ad >= o_ + off) & (ad <= o_ + off + wd)
                mask |= band & (u >= mult)
            n_thin += drop_tris("trees", m, mask)
    # additions: shrub cards (mult > 1) and canopy fill oak cards, as ledger hedge/tree generators along the span
    for r in den:
        pr = r.get("params") or {}; mult = float(pr.get("mult", pr.get("density", 1.0))); cf = float(pr.get("canopy_fill", 0) or 0)
        s1 = float(r.get("s1") or r["s"] + 10)
        if mult > 1:
            rr = dict(r, cls="hedge", asset="hedge.coyote_brush", params=dict(density=mult - 1, seed=zlib.crc32(r["id"].encode()) & 0xffff), s1=s1)
            place_linear(rr, {}); n_add += 1
        if cf > 0:
            rng = np.random.default_rng(zlib.crc32(r["id"].encode()) & 0xffff); wd = float(pr.get("width", 15.0))
            for s in np.arange(float(r["s"]), s1, 10.0 / cf):
                rr = dict(r, cls="tree_add", asset="tree.oak", s=float(s) + rng.uniform(0, 5), off=float(r.get("off") or 0) + rng.uniform(2, wd),
                          params=dict(height=float(rng.uniform(8, 13)), seed=int(rng.integers(1 << 16))))
                place_point(rr, {"collision": False}); n_add += 1
    return n_rm, n_thin, n_add


