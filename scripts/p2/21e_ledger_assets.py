#!/usr/bin/env python3
"""Phase 2, step 21e: place the dev5 scene ledger (data/scene/ledger.jsonl) into build/geometry.pkl.

Run after 21c, before 21d.  Every status=placed row is generated by scripts/p5/assets.py (config/asset_catalog.yaml)
and merged into ONE visual mesh per 200 m chunk (material "ledger", atlas build/ledger_atlas.png => one draw call per
chunk, in palomares_roadside.kn5) plus ONE collision mesh per chunk (1WALL_lg_NN, closed boxes, scripts/p2/collide.py).
It also applies the ledger's terrain and vegetation edits on top of 21/21b/21c:

  mound / ditch      gaussian or capsule height edit of the 1GRASS_t* terrain meshes (never within 0.3 m of the pavement)
  tree_remove        drops LiDAR tree / trunk-collider triangles within params.radius (default 5 m) of the point
  tree_density       span s..s1: params.mult (<1 thins 21's understorey shrub clumps, >1 adds shrub cards),
                     optional params.canopy_fill (extra oak cards per 10 m), band params.width (default 15 m) from off
  tree_add           an extra oak card + trunk collider (tree.oak)

21c skips every legacy roadside_assets entry a placed ledger row owns (same cls, same side, within +-15 m), so nothing
is placed twice (see 21c `ledger_owned`).  Idempotent: previous 21e meshes are dropped, terrain deltas and removed
tree triangles from the last run are restored first (meta["ledger21e"]).  Empty / missing ledger => only the (empty)
atlas is written and earlier 21e output is removed.
"""
