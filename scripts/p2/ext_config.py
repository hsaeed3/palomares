"""CSP ext_config.ini for palomares_road (see docs/AC_CONVENTIONS.md 'CSP / Pure').
Written into <track>/extension/ext_config.ini (CSP reads this when no repo config exists).
Vanilla AC ignores the folder, so the track still works without CSP."""
from pathlib import Path



def ext_config(materials):
    _t = lambda c: ", ".join(sorted(m for m in materials if m.startswith(f"ter_{c}_")))
    TG, TB, TL = _t("ground"), _t("bank"), _t("litter")
    FRESH = "".join(f", {k}_fresh" for k in ("paint_white", "paint_yellow", "paint_yellow_dbl") if f"{k}_fresh" in materials)
    TREES = ", ".join(sorted(m for m in materials if m.startswith("tree_") and m != "tree_trunk"))
    s = f"""; generated by scripts/p2/ext_config.py -- do not edit by hand
[ABOUT]
AUTHOR = palomares pipeline

[BASIC]
IGNORE_OTHER_CONFIGS = 0

; ---- foliage: ksTree is the shader CSP treats as foliage (translucency, wind sway, tree shading in Pure)
[SHADER_REPLACEMENT_0TREES]
MATERIALS = {TREES}
SHADER = ksTree
CULL_MODE = DOUBLESIDED
CAST_SHADOWS = 1
PROP_0 = ksAmbient, 0.5
PROP_1 = ksDiffuse, 0.55
PROP_2 = ksAlphaRef, 0.5

[SHADER_REPLACEMENT_1SHRUB]
MATERIALS = shrub
SHADER = ksTree
CULL_MODE = DOUBLESIDED
CAST_SHADOWS = 0
PROP_0 = ksAmbient, 0.5
PROP_1 = ksDiffuse, 0.5
PROP_2 = ksAlphaRef, 0.5

[WIND]
DYNAMIC_FLAGS = AUTO

[LIGHTING]
SPECULAR_MULT = 1
LIT_MULT = 1
CAR_LIGHTS_LIT_MULT = 1

[GRASS_FX]
; terrain = ksPerPixelMultiMap ter_<class>_<chunk> (scripts/p2/terrain_macro.py). Shoulder strips reuse the old
; ground/bank/litter materials and are OCCLUDING, so grass never grows on road, shoulder, kerbs, rock or decals.
GRASS_MATERIALS = {TG}, {TB}, {TL}
OCCLUDING_MATERIALS = road_asphalt, road_asphalt_fresh, road_decal, shoulder_dirt, ground, bank, litter, road_edge, rock, kerb, runoff, paint_white, paint_yellow, paint_yellow_dbl{FRESH}
OCCLUDING_MATERIALS_ALPHA =
ORIGINAL_GRASS_MATERIALS =
MASK_BLUR = 1
; colour mask: default expects green-ish texels with luminance 0.02-0.35; our albedo-calibrated spring
; textures (sRGB ~0.4-0.5, olive/brown litter) fail it, so the mask is opened up and the per-material
; configurations below decide density/shape instead
MASK_MAIN_THRESHOLD = -1
MASK_RED_THRESHOLD = 0
MASK_MIN_LUMINANCE = -1
MASK_MAX_LUMINANCE = 1
COLOR_FACTOR = 1.05
SHAPE_SIZE = 2.2
SHAPE_TIDY = 0.15
SHAPE_CUT = 0
SHAPE_WIDTH = 1.1
TEXTURE_BASE_CHANCE = 1

; A: open spring grass (ground): tall, wild, lush
[GRASS_FX_CONFIGURATION_A]
SHAPE_SIZE = 2.6
SHAPE_TIDY = 0.0
SHAPE_CUT = 0
SHAPE_WIDTH = 1.15
MASK_MAIN_THRESHOLD = -1
MASK_RED_THRESHOLD = 0
MASK_MIN_LUMINANCE = -1
MASK_MAX_LUMINANCE = 1

; B: cut banks: medium, untidy, slightly patchy where the macro map is browner
[GRASS_FX_CONFIGURATION_B]
SHAPE_SIZE = 1.9
SHAPE_TIDY = 0.0
SHAPE_CUT = 0
SHAPE_WIDTH = 1.0
MASK_MAIN_THRESHOLD = -0.3
MASK_RED_THRESHOLD = 0.3
MASK_MIN_LUMINANCE = -1
MASK_MAX_LUMINANCE = 1

; C: leaf litter under the canopy / road verge: shorter, sparser tufts
[GRASS_FX_CONFIGURATION_C]
SHAPE_SIZE = 1.4
SHAPE_TIDY = 0.3
SHAPE_CUT = 0.2
SHAPE_WIDTH = 0.9
MASK_MAIN_THRESHOLD = -0.2
MASK_RED_THRESHOLD = 0.4
MASK_MIN_LUMINANCE = -1
MASK_MAX_LUMINANCE = 1

[GRASS_FX_ADJUSTMENT_0]
MATERIALS = {TG}
; terrain is ksPerPixelMultiMap whose txDiffuse alpha is 0 (= detail everywhere): never read it as a grass mask
USE_MULTIMAP_DETAIL_MASK = 0
USE_MULTILAYER_MASK = 0
MAP = A

[GRASS_FX_ADJUSTMENT_1]
MATERIALS = {TB}
; terrain is ksPerPixelMultiMap whose txDiffuse alpha is 0 (= detail everywhere): never read it as a grass mask
USE_MULTIMAP_DETAIL_MASK = 0
USE_MULTILAYER_MASK = 0
MAP = B

[GRASS_FX_ADJUSTMENT_2]
MATERIALS = {TL}
; terrain is ksPerPixelMultiMap whose txDiffuse alpha is 0 (= detail everywhere): never read it as a grass mask
USE_MULTIMAP_DETAIL_MASK = 0
USE_MULTILAYER_MASK = 0
MAP = C

[RAIN_FX]
PUDDLES_MATERIALS = road_asphalt, road_asphalt_fresh, road_decal, shoulder_dirt
SOAKING_MATERIALS = road_asphalt, road_asphalt_fresh, road_decal, shoulder_dirt, litter, rock, {TL}
ROUGH_MATERIALS = ground, bank, litter, {TG}, {TB}, {TL}
SMOOTH_MATERIALS = guardrail, dressing, rpm_yellow
LINES_MATERIALS = paint_white, paint_yellow, paint_yellow_dbl
"""
    # sanity: every material named above must exist in the kn5s
    import re
    named = set()
    for k, v in re.findall(r"^(MATERIALS|\w+_MATERIALS(?:_ALPHA)?)[ \t]*=[ \t]*(.*)$", s, re.M):
        named |= {x.strip() for x in v.split(",") if x.strip()}
    missing = named - set(materials)
    assert not missing, f"ext_config names unknown materials: {missing}"
    return s


def write_ext_config(track: Path, materials):
    d = Path(track) / "extension"; d.mkdir(parents=True, exist_ok=True)
    (d / "ext_config.ini").write_text(ext_config(materials))
    return d / "ext_config.ini"
